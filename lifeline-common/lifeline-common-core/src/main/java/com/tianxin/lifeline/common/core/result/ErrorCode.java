package com.tianxin.lifeline.common.core.result;

import lombok.AllArgsConstructor;
import lombok.Getter;

/**
 * 全平台统一错误码枚举。
 *
 * <p>错误码分段规则：
 * <ul>
 *     <li>10000 段：通用错误</li>
 *     <li>20000 段：权限认证错误</li>
 *     <li>30000 段：管网资产错误</li>
 *     <li>40000 段：预警预报错误</li>
 *     <li>50000 段：运维工单错误</li>
 *     <li>60000 段：预案处置错误</li>
 *     <li>70000 段：施工监管错误</li>
 *     <li>80000 段：AI能力网关错误</li>
 *     <li>90000 段：区块链溯源错误</li>
 * </ul>
 */
@Getter
@AllArgsConstructor
public enum ErrorCode {

    /* ==================== 通用 10000 ==================== */
    /** 通用业务错误 */
    COMMON_ERROR(10000, "系统繁忙，请稍后重试"),
    /** 参数校验错误 */
    PARAM_INVALID(10001, "请求参数不合法"),
    /** 资源不存在 */
    RESOURCE_NOT_FOUND(10002, "请求的资源不存在"),
    /** 重复提交 */
    DUPLICATE_REQUEST(10003, "请勿重复提交"),
    /** 第三方服务调用失败 */
    REMOTE_CALL_ERROR(10004, "远程服务调用失败"),

    /* ==================== 权限认证 20000 ==================== */
    /** 未认证 */
    UNAUTHORIZED(20000, "未登录或登录已过期"),
    /** 无权限 */
    FORBIDDEN(20001, "无访问权限"),
    /** token 无效 */
    TOKEN_INVALID(20002, "令牌无效"),
    /** token 过期 */
    TOKEN_EXPIRED(20003, "令牌已过期"),
    /** 用户名或密码错误 */
    LOGIN_FAILED(20004, "用户名或密码错误"),
    /** 账号被禁用 */
    ACCOUNT_DISABLED(20005, "账号已被禁用"),

    /* ==================== 管网资产 30000 ==================== */
    /** 管网不存在 */
    PIPE_NOT_FOUND(30000, "管网记录不存在"),
    /** 设备不存在 */
    DEVICE_NOT_FOUND(30001, "设备不存在"),
    /** 井盖不存在 */
    MANHOLE_NOT_FOUND(30002, "井盖不存在"),
    /** 管网状态不允许该操作 */
    PIPE_STATUS_INVALID(30003, "管网当前状态不允许该操作"),

    /* ==================== 预警预报 40000 ==================== */
    /** 预警事件不存在 */
    WARNING_NOT_FOUND(40000, "预警事件不存在"),
    /** 预警事件状态不允许该操作 */
    WARNING_STATUS_INVALID(40001, "预警事件当前状态不允许该操作"),
    /** 预警规则不存在 */
    WARNING_RULE_NOT_FOUND(40002, "预警规则不存在"),
    /** 预报报告不存在 */
    FORECAST_NOT_FOUND(40003, "超前预报记录不存在"),

    /* ==================== 运维工单 50000 ==================== */
    /** 工单不存在 */
    ORDER_NOT_FOUND(50000, "工单不存在"),
    /** 工单状态不允许该操作 */
    ORDER_STATUS_INVALID(50001, "工单当前状态不允许该操作"),
    /** 巡检计划不存在 */
    INSPECTION_NOT_FOUND(50002, "巡检计划不存在"),

    /* ==================== 预案处置 60000 ==================== */
    /** 预案模板不存在 */
    PLAN_NOT_FOUND(60000, "预案不存在"),
    /** 预案状态不允许该操作 */
    PLAN_STATUS_INVALID(60001, "预案当前状态不允许该操作"),

    /* ==================== 施工监管 70000 ==================== */
    /** 施工项目不存在 */
    CONSTRUCTION_NOT_FOUND(70000, "施工项目不存在"),
    /** 质检流程错误 */
    INSPECT_PROCESS_ERROR(70001, "工序质检提交失败"),

    /* ==================== AI能力网关 80000 ==================== */
    /** AI模型调用失败 */
    AI_INVOKE_ERROR(80000, "AI能力调用失败"),
    /** AI限流降级 */
    AI_RATE_LIMITED(80001, "AI请求过于频繁，请稍后重试"),

    /* ==================== 区块链溯源 90000 ==================== */
    /** 上链存证失败 */
    BLOCKCHAIN_EVIDENCE_ERROR(90000, "上链存证失败"),
    /** DID不存在 */
    DID_NOT_FOUND(90001, "管道DID不存在");

    /** 错误码 */
    private final int code;

    /** 错误描述 */
    private final String message;
}
